            title=title,
            slug=slug,
            original_title=title,
            description=description,
            year=2026,
            duration=minutes,
            genres=genres,
            rating=Decimal(rating),
            rating_count=0,
            director=director,
            cast=cast,
            age="0+" if "Анимация" in genres else "16+" if "Ужаси" in genres else "12+",
            language="Български",
            subtitles="Български",
            poster=f"/images/originals/{slug}-poster.svg",
            backdrop=f"/images/originals/{slug}-backdrop.svg",
            trailer="",
            release_date="2026-11-20" if i >= 12 else "2026-10-01",
            status="upcoming" if i >= 12 else "active",
            featured=i in (0, 1, 5),
            is_demo=True,
